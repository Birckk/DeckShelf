import { createHash } from 'node:crypto';
import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';

const root = resolve(import.meta.dirname, '..');
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const output = join(root, 'release');
const staging = join(root, 'build/windows');
await mkdir(output, { recursive: true });
const zip = `DeckShelf-${pkg.version}-windows-x64.zip`;
const installer = `DeckShelf-Setup-${pkg.version}-x64.exe`;
const require = createRequire(import.meta.url);
const asar = require('@electron/asar');
const packed = join(staging, 'win-unpacked');
const entries = asar.listPackage(join(packed, 'resources/app.asar')).map(path => path.replaceAll('\\', '/'));
for (const required of ['/desktop/main.mjs', '/desktop/request.mjs', '/dist/index.html', '/server/api.mjs', '/server/sources.mjs', '/shared/formats.mjs']) assert.ok(entries.includes(required), `Missing ${required}`);
for (const entry of entries) assert.ok(/^\/(desktop|dist|server|shared)(\/|$)|^\/package.json$/.test(entry), `Unexpected packaged file: ${entry}`);
for (const file of ['LICENSE.electron.txt', 'LICENSES.chromium.html', 'resources/LICENSE.md', 'resources/THIRD_PARTY_NOTICES.md', 'resources/notices/dependencies.json', 'resources/notices/artwork.json']) await readFile(join(packed, file));
for (const file of [zip, installer]) await copyFile(join(staging, file), join(output, file));
await copyFile(join(root, 'docs/DESKTOP.md'), join(output, 'DESKTOP.md'));
await copyFile(join(root, 'docs/THIRD_PARTY_NOTICES.md'), join(output, 'THIRD_PARTY_NOTICES.md'));
await copyFile(join(root, 'docs/RELEASE_NOTES.md'), join(output, 'RELEASE_NOTES.md'));
await copyFile(join(root, 'docs/VALIDATION.md'), join(output, 'VALIDATION.md'));
const metadata = { version: pkg.version, platform: 'win32', arch: 'x64', electron: pkg.devDependencies.electron, revision: process.env.GITHUB_SHA || 'local-build', signed: false };
await writeFile(join(output, 'build-info.json'), JSON.stringify(metadata, null, 2) + '\n');
const files = [installer, zip, 'DESKTOP.md', 'THIRD_PARTY_NOTICES.md', 'RELEASE_NOTES.md', 'VALIDATION.md', 'build-info.json'];
const checksums = await Promise.all(files.map(async file => `${createHash('sha256').update(await readFile(join(output, file))).digest('hex')}  ${file}`));
await writeFile(join(output, 'SHA256SUMS.txt'), checksums.join('\n') + '\n');
console.log(`Release assets ready in ${output}. Nothing published.`);
