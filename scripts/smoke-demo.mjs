import { chromium, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
const snapshot = JSON.parse(await readFile(new URL('../src/data/precons.json', import.meta.url)));
const legacy = JSON.parse(await readFile(new URL('../src/data/decks.json', import.meta.url)));
const base = process.env.BASE_URL || 'http://127.0.0.1:4331';
const key = 'commander-archive.collection.v1';
const browser = await chromium.launch();
await mkdir('qa/demo', { recursive: true });
const errors = [];
try {
 for (const viewport of [{ width: 1440, height: 960 }, { width: 390, height: 844 }]) {
  const context = await browser.newContext({ viewport, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  const apiCalls = [];
  page.on('request', r => { if (r.url().includes('/api/')) apiCalls.push(r.url()); });
  const started = Date.now();
  await page.goto(base);
  await expect(page.locator('.count-badge')).toHaveText(String(snapshot.decks.length));
  await expect(page.getByRole('button', { name: 'Collection', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.collection-grid')).toHaveClass(/collection-layout-art collection-size-1/);
  await page.getByRole('button', { name: 'Cards', exact: true }).click();
  await expect(page.locator('.studio-card')).toHaveCount(7);
  const startup = Date.now() - started;
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect.poll(() => page.locator('.studio-card.is-current img').evaluateAll(images => images.every(i => i.complete && i.naturalWidth > 0) && images.length > 0), { timeout: 20000 }).toBe(true);
  await page.screenshot({ path: `qa/demo/${viewport.width}-cards.png` });
  await page.getByRole('button', { name: 'Collection', exact: true }).click();
  await expect(page.locator('.collection-tile')).toHaveCount(snapshot.decks.length);
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await page.getByRole('button', { name: 'Filter Blue', exact: true }).click();
  await expect(page.locator('.collection-tile')).toHaveCount(snapshot.decks.filter(d => d.colors.includes('U')).length);
  await page.getByRole('button', { name: 'Filter Blue', exact: true }).click();
  const target = snapshot.decks[0];
  await page.getByRole('textbox', { name: 'Search decks', exact: true }).fill(target.commanders[0].name);
  const pool = snapshot.decks.filter(d => JSON.stringify(d).toLowerCase().includes(target.commanders[0].name.toLowerCase()));
  await expect(page.locator('.collection-tile')).toHaveCount(pool.length);
  await page.getByRole('button', { name: `Exclude ${target.name} from picker`, exact: true }).click();
  await page.getByRole('textbox', { name: 'Search decks', exact: true }).fill('');
  await page.getByRole('group', { name: 'Collection view' }).getByRole('button', { name: 'Pick a deck', exact: true }).click();
  await expect(page.locator('.spin-button')).toHaveAttribute('title', `Each eligible deck has a 1 in ${snapshot.decks.length - 1} chance.`);
  await page.locator('.spin-button').click();
  await expect(page.locator('.helix-reveal')).toBeVisible();
  await expect.poll(() => page.locator('.helix-reveal img').evaluateAll(images => images.every(i => i.complete && i.naturalWidth > 0) && images.length > 0), { timeout: 20000 }).toBe(true);
  await page.screenshot({ path: `qa/demo/${viewport.width}-picker.png` });
  await page.getByRole('button', { name: /^My collection/ }).click();
  await expect(page.getByRole('switch', { name: 'Enable Official Commander precons', exact: true })).toBeChecked();
  await expect(page.getByText('Complete at snapshot date.', { exact: false })).toBeVisible();
  await page.screenshot({ path: `qa/demo/${viewport.width}-overview.png` });
  await page.getByRole('switch', { name: 'Enable Official Commander precons', exact: true }).uncheck();
  await expect(page.locator('.manager-heading p')).toContainText('0 on display');
  await page.getByRole('switch', { name: 'Enable Official Commander precons', exact: true }).check();
  await page.getByRole('button', { name: 'Remove precons', exact: true }).click();
  await expect(page.locator('.manager-heading p')).toContainText('0 on display');
  await page.getByRole('button', { name: 'Restore precons', exact: true }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export backup', exact: true }).click();
  const download = await downloadEvent;
  const backup = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(backup.demo.decks.length).toBe(snapshot.decks.length);
  expect(backup.excluded).toContain(target.id);
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: /^My collection/ }).click();
  await page.getByRole('button', { name: 'Start my collection', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Add from Archidekt', exact: true })).toBeVisible();
  await expect(page.locator('.manager-heading p')).toContainText('0 on display');
  await page.screenshot({ path: `qa/demo/${viewport.width}-personal.png` });
  expect(apiCalls).toEqual([]);
  const old = { version: 1, hidden: [legacy[0].id], excluded: [legacy[1].id], added: [], disabledGroups: [] };
  await page.locator('input[type=file]').setInputFiles({ name: 'old-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(old)) });
  await page.getByRole('button', { name: 'Restore this backup', exact: true }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.reload();
  expect(await page.evaluate(k => JSON.parse(localStorage.getItem(k)), key)).toEqual(old);
  await expect(page.locator('.count-badge')).toHaveText('28');
  // Reimport the fresh backup through the same UI and verify demo state survives.
  await page.getByRole('button', { name: /^My collection/ }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'demo-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await page.getByRole('button', { name: 'Restore this backup', exact: true }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.reload();
  expect(await page.evaluate(k => JSON.parse(localStorage.getItem(k)), key)).toEqual(backup);
  await page.evaluate(k => localStorage.setItem(k, '{broken'), key);
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('has not been overwritten');
  await page.getByRole('button', { name: /^My collection/ }).click();
  await page.getByRole('button', { name: 'Add precons', exact: true }).click();
  expect(await page.evaluate(k => localStorage.getItem(k), key)).toBe('{broken');
  await page.locator('input[type=file]').setInputFiles({ name: 'recovery.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(old)) });
  await page.getByRole('button', { name: 'Restore this backup', exact: true }).click();
  await expect.poll(() => page.evaluate(k => JSON.parse(localStorage.getItem(k)), key)).toEqual(old);
  console.log(`${viewport.width}px: full demo, filters, picker, remove/restore, personal start, v1 backup and corrupt recovery passed; first view ${startup}ms; no API requests.`);
  await context.close();
 }
 expect(errors).toEqual([]);
} finally { await browser.close(); }
